// Ключи от длинных к коротким: "пса свободный" должен победить "пса".
const METRIC_KEYS_BY_LENGTH = Object.entries(METRIC_NAME_MAP)
  .sort((a, b) => b[0].length - a[0].length)
  .map(([key, canonical]) => ({ key, canonical, re: key.length <= 4 ? wordRe(key) : null }))

// Точные алиасы из METRICS_CONFIG (регистронезависимо).
const ALIAS_EXACT: Record<string, string> = {}
for (const config of Object.values(METRICS_CONFIG)) {
  ALIAS_EXACT[config.name.toLowerCase()] = config.name
  for (const alias of config.aliases) ALIAS_EXACT[alias.toLowerCase()] = config.name
}

/**
 * Квалификаторы в квадратных скобках ("[масса / объем]", "[# / объем]") — служебные, убираем целиком,
 * иначе "Гемоглобин [масса / объем] в крови" отсекается исключением 'объем'.
 * Содержимое круглых скобок оставляем: там аббревиатуры ("Гемоглобин (HGB)").
 */
function clean(rowName: string): string {
  return rowName
    .replace(/\[[^\]]*\]/g, ' ')
    .replace(/[(){}]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()
}

/**
 * Каноническое название показателя или null.
 * @param rowName название строки таблицы / ключ keyValues
 * @param unit    единица измерения, если известна — различает "Нейтрофилы 4.1 ×10⁹/л" и "Нейтрофилы 54.8 %"
 */
export function canonicalizeMetricName(rowName: string | undefined | null, unit?: string | null): string | null {
  if (!rowName) return null
  const cleaned = clean(rowName)
  if (cleaned.length < 2) return null
  const unitLower = (unit || '').trim().toLowerCase()
  const unitIsPercent = unitLower.includes('%')

  if (unitLower && JUNK_UNIT_RE.test(unitLower)) return null
  if (unitLower && PER_MICROLITER_UNIT_RE.test(unitLower)) return null
  if (PRICE_CODE_RE.test(cleaned)) return null
  if (URINE_RE.test(cleaned)) return null

  if (HBA1C_RE.test(cleaned)) return 'Гликированный гемоглобин'
  if (MCV_RE.test(cleaned) && !NOT_MCV_RE.test(cleaned)) return unitIsPercent ? null : 'MCV'

  for (const re of EXCLUDE_WORDS) if (re.test(cleaned)) return null
  for (const ex of EXCLUDE_SUBSTRINGS) if (cleaned.includes(ex)) return null

  for (const subtype of LEUKOCYTE_SUBTYPES) {
    if (!subtype.re.test(cleaned)) continue
    const isPercent = unitIsPercent || PERCENT_NAME_RE.test(cleaned)
    return isPercent ? subtype.pct : subtype.abs
  }

  const canonical = ALIAS_EXACT[cleaned] ?? METRIC_NAME_MAP[cleaned] ?? matchByKeys(cleaned)
  if (!canonical) return null
  // "Альбумин: 45 %" (фракция электрофореза), "Тромбоциты: 0.2 %" — не те метрики.
  if (unitIsPercent && !PERCENT_METRICS.has(canonical)) return null
  return canonical
}

function matchByKeys(cleaned: string): string | null {
  for (const { key, canonical, re } of METRIC_KEYS_BY_LENGTH) {
    if (re ? re.test(cleaned) : cleaned.includes(key)) return canonical
  }
  return null
}
