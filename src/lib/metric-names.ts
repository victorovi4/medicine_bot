// Гликированный гемоглобин проверяем ДО исключений: 'гликир' в списке, чтобы HbA1c
// не попадал в обычный "Гемоглобин" через подстроку.
const HBA1C_RE = /hba1c|гликир|гликозилир/

// MCV проверяем ДО исключений ('средн', 'объем'): "Средний объем эритроцита (MCV)",
// "Ср.объем эритр (MCV)", "MCV". Но не RDW ("ширина распределения эритроцитов по объему")
// и не MPV ("средний объем тромбоцита").
const MCV_RE = new RegExp(`${B}mcv${E}|объ[её]м\\w*\\s+эритр`)
const NOT_MCV_RE = /тромбоц|mpv|pmv|pdw|rdw|ширин|распред|отклон|вариац/

// Лейкоцитарная формула: абсолютные (×10⁹/л) и относительные (%) значения — разные метрики.
// Проверяем ДО общего словаря, иначе "Нейтрофилы / 100 лейкоцитов" уйдёт в "Лейкоциты".
const LEUKOCYTE_SUBTYPES: Array<{ re: RegExp; abs: string | null; pct: string | null }> = [
  { re: new RegExp(`нейтроф|neut|${B}ачн${E}`), abs: 'Нейтрофилы', pct: 'Нейтрофилы %' },
  { re: /лимфоц|lym/, abs: 'Лимфоциты', pct: 'Лимфоциты %' },
  { re: /моноцит|mono|mon[#%]/, abs: 'Моноциты', pct: 'Моноциты %' },
  { re: /эозиноф|базоф|baso/, abs: null, pct: null }, // не отслеживаем
]
const PERCENT_NAME_RE = /%|относительн|отн\.|\/\s?100/

